// Writes src/contracts/*.ts from the JSON Schemas the Rust engine publishes (docs/schemas).
// Run `pnpm run contracts` after a schema changes and commit the result; `--check` fails when
// the committed files are stale, which is what the gate runs.
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { compile } from 'json-schema-to-typescript';

const schemas = ['ledger', 'repository-context', 'review-job-result'];
const source = new URL('../../../docs/schemas/', import.meta.url);
const target = new URL('../src/contracts/', import.meta.url);
const check = process.argv.includes('--check');

await mkdir(target, { recursive: true });
let stale = false;
for (const name of schemas) {
  const schema = JSON.parse(await readFile(new URL(`${name}.schema.json`, source), 'utf8'));
  const ts = await compile(schema, schema.title ?? name, {
    additionalProperties: false,
    bannerComment: `/* Generated by scripts/contracts.mjs from docs/schemas/${name}.schema.json. Do not edit. */`,
    format: false,
    strictIndexSignatures: true,
    unreachableDefinitions: true,
  });
  const file = new URL(`${name}.ts`, target);
  if (check) {
    const current = await readFile(file, 'utf8').catch(() => '');
    if (current !== ts) {
      console.error(`src/contracts/${name}.ts is out of date: run pnpm run contracts`);
      stale = true;
    }
  } else {
    await writeFile(file, ts);
  }
}
process.exit(stale ? 1 : 0);
